"""
database.py
Handles all SQLite setup and provides a helper to get a DB connection.
"""

import sqlite3
import os

# Allow tests to override the DB path via an environment variable
DB_PATH = os.environ.get(
    "DB_OVERRIDE",
    os.path.join(os.path.dirname(__file__), "study_planner.db")
)


def get_connection():
    """
    Open and return a connection to the SQLite database.
    row_factory = sqlite3.Row lets us access columns by name: row["name"]
    """
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    return conn


def init_db():
    """
    Create all tables if they don't already exist.
    Safe to call every time the app starts.
    """
    conn = get_connection()
    cursor = conn.cursor()

    # ── subjects ──────────────────────────────────────────────────────
    # priority: 1=low, 2=medium, 3=high
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS subjects (
            id             INTEGER PRIMARY KEY AUTOINCREMENT,
            name           TEXT    NOT NULL,
            syllabus_units INTEGER NOT NULL DEFAULT 1,
            exam_date      TEXT    NOT NULL,
            priority       INTEGER NOT NULL DEFAULT 2
                             CHECK(priority IN (1, 2, 3)),
            created_at     TEXT    NOT NULL DEFAULT (date('now'))
        )
    """)

    # ── availability ──────────────────────────────────────────────────
    # day_of_week: 0=Monday … 6=Sunday  (matches Python's weekday())
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS availability (
            id                       INTEGER PRIMARY KEY AUTOINCREMENT,
            day_of_week              INTEGER NOT NULL
                                       CHECK(day_of_week BETWEEN 0 AND 6),
            start_time               TEXT    NOT NULL,
            end_time                 TEXT    NOT NULL,
            session_duration_minutes INTEGER NOT NULL DEFAULT 60,
            break_duration_minutes   INTEGER NOT NULL DEFAULT 10,
            UNIQUE(day_of_week)
        )
    """)

    # Add break_duration_minutes to existing DBs that were created before this column
    existing_cols = [row[1] for row in cursor.execute("PRAGMA table_info(availability)").fetchall()]
    if "break_duration_minutes" not in existing_cols:
        cursor.execute("ALTER TABLE availability ADD COLUMN break_duration_minutes INTEGER NOT NULL DEFAULT 10")

    # ── study_sessions ────────────────────────────────────────────────
    # Generated by the scheduling algorithm (Phase 4).
    # completed: 0=pending, 1=done
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS study_sessions (
            id          INTEGER PRIMARY KEY AUTOINCREMENT,
            subject_id  INTEGER NOT NULL
                          REFERENCES subjects(id) ON DELETE CASCADE,
            date        TEXT    NOT NULL,
            start_time  TEXT    NOT NULL,
            end_time    TEXT    NOT NULL,
            completed   INTEGER NOT NULL DEFAULT 0
                          CHECK(completed IN (0, 1)),
            created_at  TEXT    NOT NULL DEFAULT (datetime('now'))
        )
    """)

    conn.commit()
    conn.close()
    print("✅ Database initialised –", DB_PATH)


if __name__ == "__main__":
    init_db()
